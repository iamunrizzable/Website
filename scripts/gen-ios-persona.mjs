// Generates ios/Hallie/Persona.swift from the website's persona so the app and site stay identical.
import { readFileSync, writeFileSync } from 'node:fs'
const src = readFileSync(new URL('../app/hallie/local/prompt.js', import.meta.url), 'utf8')
const m = src.match(/HALLIE_LOCAL_PROMPT\s*=\s*`([\s\S]*?)`;?\s*$/)
if (!m) throw new Error('persona not found')
const text = m[1].replace(/\\`/g, '`').replace(/\\\$/g, '$').replace(/\\\\/g, '\\')
if (text.includes('"""#')) throw new Error('unsafe delimiter in persona')
writeFileSync(new URL('../ios/Hallie/Persona.swift', import.meta.url),
  `// GENERATED by scripts/gen-ios-persona.mjs from app/hallie/local/prompt.js. Do not edit.\nlet halliePersona = #"""\n${text}\n"""#\n`)
console.log('wrote Persona.swift', text.length, 'chars')

// The Writer's prompts: Hallie's soul and Tyler's voice baseline, evaluated from the lib files.
const { HALLIE_SOUL } = await import('../lib/hallie-soul.js')
const { TYLER_VOICE_BASELINE } = await import('../lib/tyler-voice-baseline.js')
if (HALLIE_SOUL.includes('"""#')) throw new Error('unsafe delimiter in soul')
const esc = (l) => JSON.stringify(l)
writeFileSync(new URL('../ios/Hallie/WriterData.swift', import.meta.url),
  `// GENERATED by scripts/gen-ios-persona.mjs from lib/hallie-soul.js and lib/tyler-voice-baseline.js. Do not edit.\nlet halliePersonaFull = #"""\n${HALLIE_SOUL}\n"""#\nlet tylerVoiceBaseline: [String] = [\n${TYLER_VOICE_BASELINE.map(l => '  ' + esc(l) + ',').join('\n')}\n]\n`)
console.log('wrote WriterData.swift', HALLIE_SOUL.length, TYLER_VOICE_BASELINE.length)
